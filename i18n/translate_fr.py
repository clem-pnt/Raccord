def main():
    ts_path = "i18n/raccord_fr.ts"
    tree = ET.parse(ts_path)
    root = tree.getroot()
    root.set("language", "fr_FR")
    missing = []
    for ctx in root.iter("context"):
        if ctx.find("name").text == "Effects":
            continue   # filled from FX below
        for m in ctx.iter("message"):
            src = m.find("source").text or ""
            tr = m.find("translation")
            val = UI.get(src)
            if val is None:
                missing.append(src)
                continue
            for n in list(tr):
                tr.remove(n)
            tr.attrib.pop("type", None)
            if m.get("numerus") == "yes":
                forms = val if isinstance(val, tuple) else (val, val)
                tr.text = None
                for f in forms:
                    e = ET.SubElement(tr, "numerusform")
                    e.text = f
            else:
                tr.text = val[0] if isinstance(val, tuple) else val
    # Contexts for runtime strings: effects, workspaces, tool tips.
    def add_context(name, entries):
        c = next((c for c in root.findall("context") if c.find("name").text == name), None)
        if c is None:
            c = ET.SubElement(root, "context")
            ET.SubElement(c, "name").text = name
        have = {m.find("source").text for m in c.findall("message")}
        for src, dst in entries:
            if src in have:
                continue
            m = ET.SubElement(c, "message")
            ET.SubElement(m, "source").text = src
            ET.SubElement(m, "translation").text = dst
    fx_strings = []
    if len(sys.argv) > 1:
        fx_strings = [l.rstrip("\n") for l in open(sys.argv[1], encoding="utf-8") if l.strip()]
    fx = []
    for s in fx_strings:
        if s in FX:
            fx.append((s, FX[s]))
        else:
            missing.append("[fx] " + s)
    add_context("Effects", fx)
    add_context("rc::MainWindow", [(s, UI[s]) for s in ("Editing", "Color", "Audio", "Effects", "Assembly")])
    add_context("rc::TimelinePanel", [(s, UI[s]) for s in UI if s.endswith(")") and "Tool" in s or s in ("Track Select Forward (A)",)])
    ET.indent(tree)
    tree.write(ts_path, encoding="utf-8", xml_declaration=True)
    for s in missing:
        print("missing:", repr(s))


